def densify(points, minimum=420):
    # Extra collinear points do not add invented coastal wiggles.
    out = list(points)
    while len(out) < minimum:
        i = max(range(len(out)), key=lambda j: sum((out[j][k]-out[(j+1)%len(out)][k])**2 for k in (0,1)))
        out.insert(i+1, [(out[i][k]+out[(i+1)%len(out)][k])/2 for k in (0,1)])
    return [[round(x,6),round(y,6)] for x,y in out]


